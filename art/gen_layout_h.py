"""Writes plugin/Layout.h and plugin/HelpText.h from art/layout.py, art/build/meter_geometry.json
and the mockup's help texts, so the window places everything exactly where the renders put it.

    python3 art/gen_layout_h.py
"""
import json
import os
import re

import layout as L

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "plugin", "Layout.h")
geo = json.load(open(os.path.join(HERE, "build", "meter_geometry.json")))

KINDS = {"large": 0, "med": 1, "small": 2, "sel": 3}
TYPES = {"knob": "Knob", "toggle": "Toggle", "button": "Button", "meter": "Meter", "lamp": "Lamp", "crt": "Screen"}


def f(v):
    return f"{float(v):.4f}f"


group_names = list(L.LIT_GROUPS.keys()) + ["tray"]
group_of = {cid: gi for gi, name in enumerate(group_names) if name != "tray" for cid in L.LIT_GROUPS[name]}
group_of["sp_in"] = group_names.index("tray")
tray_in = next(c for c in L.TRAY_CONTROLS if c["id"] == "sp_in")


def group_rect(name):
    if name == "tray":
        return L.lit_rect(tray_in)
    rects = [L.lit_rect(L.control(i)) for i in L.LIT_GROUPS[name]]
    x0, y0 = min(r[0] for r in rects), min(r[1] for r in rects)
    return x0, y0, max(r[0] + r[2] for r in rects) - x0, max(r[1] + r[3] for r in rects) - y0


lines = []
w = lines.append
w("// Generated by art/gen_layout_h.py from art/layout.py: do not edit by hand.")
w("// Points at 100%; the art is rendered at 2x. The tray has its own canvas, under the panel.")
w("#pragma once")
w("")
w("namespace layout {")
w("")
w(f"constexpr float W = {f(L.W)}, H = {f(L.H)}, kTrayH = {f(L.TRAY_H)};")
w(f"constexpr int kArtScale = {L.SCALE};")
w(f"constexpr float kSweep = {f(L.SWEEP)};     // continuous knobs: +-degrees")
w(f"constexpr float kKnobRadius[4] = {{{', '.join(f(L.KNOBS[k]) for k in ('large', 'med', 'small', 'sel'))}}};")
w("enum Kind { kLarge, kMed, kSmall, kSel };")
w(f"constexpr int kNumSelAngles = {len(L.SEL_ANGLES)};")
w(f"constexpr float kSelAngles[kNumSelAngles] = {{{', '.join(f(a) for a in L.SEL_ANGLES)}}};   // frames of knob_sel.png")
w("enum Type { Knob, Toggle, Button, Meter, Lamp, Screen };")
w("")
w("struct Control {")
w("    const char* id;")
w("    Type type;")
w("    int kind;           // knobs: Kind; meters: 0 loudness, 1 punch")
w("    float x, y, w, h;   // centre; w and h for buttons, meters and the screen")
w("    int nSteps;         // selectors")
w("    float steps[10];    // selector angles (degrees)")
w("    int pointer;        // pointer paint (kPointerColours), or -1 for ivory")
w("    int litGroup;       // which lit-patch image this control's lit state is cut from, or -1")
w("    float lx, ly, lw, lh;   // the patch of panel that changes when it lights")
w("    bool tray;          // on the SPACE tray (y measured from the tray's top)")
w("};")
w("")
cap_names = list(L.POINTER_COLOURS.keys())
w(f"constexpr int kNumPointerColours = {len(cap_names)};")
w("constexpr float kPointerColours[kNumPointerColours][3] = {" + ", ".join("{" + ", ".join(f(v) for v in L.POINTER_COLOURS[n]) + "}" for n in cap_names) + "};   // " + ", ".join(cap_names))
w(f"constexpr float kCapR = {f(L.CAP_R)};   // cap radius / knob radius")
w("")
w(f"constexpr int kNumLitGroups = {len(group_names)};")
w("inline const char* const kLitGroupNames[kNumLitGroups] = {" + ", ".join(f'"{n}"' for n in group_names) + "};")
w("constexpr bool kLitGroupGreen[kNumLitGroups] = {" + ", ".join("true" if n.startswith("key_") else "false" for n in group_names) + "};")
w("constexpr float kLitGroupRect[kNumLitGroups][4] = {" + ", ".join("{" + ", ".join(f(v) for v in group_rect(n)) + "}" for n in group_names) + "};")
w("")


def row(c, tray):
    t = TYPES[c["type"]]
    kind = 0
    if c["type"] == "knob":
        kind = KINDS[c["kind"]]
    elif c["type"] == "meter":
        kind = 0 if c["kind"] == "lufs" else 1
    cw, ch = c.get("w", 0), c.get("h", 0)
    if c["type"] == "lamp":
        cw = ch = 2 * c["r"]
    st = c.get("steps") or []
    steps = ", ".join(f(a) for a in (st + [0] * (10 - len(st)))[:10])
    nsteps = len(st) if c["type"] == "knob" and c["kind"] == "sel" else 0
    cap = cap_names.index(L.POINTERS[c["id"]]) if c["id"] in L.POINTERS else -1
    gi = group_of.get(c["id"], -1)
    lr = L.lit_rect(c) if gi >= 0 else (0, 0, 0, 0)
    return f'    {{"{c["id"]}", {t}, {kind}, {f(c["x"])}, {f(c["y"])}, {f(cw)}, {f(ch)}, {nsteps}, {{{steps}}}, {cap}, {gi}, {", ".join(f(v) for v in lr)}, {"true" if tray else "false"}}},'


w("inline const Control kControls[] = {")
for c in L.CONTROLS:
    w(row(c, False))
for c in L.TRAY_CONTROLS:
    w(row(c, True))
w("};")
w("constexpr int kNumControls = int(sizeof(kControls) / sizeof(kControls[0]));")
w("")
F, G = L.FACE, L.GRID
w("// The screen: the glass face, and the etched grid inside it.")
w(f"constexpr float kFaceX = {f(F['x0'])}, kFaceY = {f(F['y0'])}, kFaceW = {f(F['x1'] - F['x0'])}, kFaceH = {f(F['y1'] - F['y0'])};")
w(f"constexpr float kGridX = {f(G['x0'])}, kGridY = {f(G['y0'])}, kGridW = {f(G['x1'] - G['x0'])}, kGridH = {f(G['y1'] - G['y0'])};")
w("")
w("// The two readouts (drum wheels): centre, size.")
for r in L.READOUTS:
    nm = "Lufs" if r["id"] == "r_lufs" else "Tp"
    w(f"constexpr float kReadout{nm}[4] = {{{f(r['x'])}, {f(r['y'])}, {f(r['w'])}, {f(r['h'])}}};")
pt, st = L.PRESET_TAPE, L.SECT_TAPE
w(f"constexpr float kPresetTapeX = {f(pt['x'])}, kPresetTapeY = {f(pt['y'])}, kPresetTapeW = {f(pt['w'])}, kPresetTapeH = {f(pt['h'])}, kPresetTapeAngle = {f(pt['angle'])};")
w(f"constexpr float kSectTapeX = {f(st['x'])}, kSectTapeY = {f(st['y'])}, kSectTapeW = {f(st['w'])}, kSectTapeH = {f(st['h'])}, kSectTapeAngle = {f(st['angle'])};")
w(f"constexpr int kNumSections = {L.NUM_SECT};")
w("constexpr float kSectKeyX[kNumSections] = {" + ", ".join(f(L.control(f"sec_{i + 1}")["x"]) for i in range(L.NUM_SECT)) + "};")
la = L.SPACE_LATCH
w(f"constexpr float kLatchX = {f(la['x'])}, kLatchY = {f(la['y'])}, kLatchR = {f(la['r'])};")
w("")
w("// Meters: the face window sits `inset` inside the meter; the needle pivots at")
w("// (pivotX, pivotY) from the window's top-left and the scale arc has radius `radius`.")
w(f"constexpr float kMeterInset = {f(geo['inset'])};")
g = geo["lufs"]
w(f"constexpr float kMeterFaceW = {f(g['fw'])}, kMeterFaceH = {f(g['fh'])}, kMeterPivotX = {f(g['pivot'][0])}, kMeterPivotY = {f(g['pivot'][1])}, kMeterRadius = {f(g['radius'])};")
w("constexpr float kMeterSpan = 42.0000f;   // degrees either side of upright at the ends of the scale")
w("")
w("}  // namespace layout")
w("")
open(OUT, "w").write("\n".join(lines))
print("wrote", os.path.normpath(OUT))

# ---- the help strip's texts, from the mockup
src = open(os.path.join(HERE, "mockup", "logic.js"), encoding="utf-8").read()
songwide = re.search(r'const SONGWIDE = "([^"]*)";', src).group(1)
t0 = src.index("const T = {")
block = src[t0:src.index("const st = this.state", t0)]
NOT_YET = set()
out = ["// Generated by art/gen_layout_h.py from art/mockup/logic.js: do not edit by hand.", "#pragma once", "",
       "namespace help {", "struct Entry { const char* id; const char* name; const char* range; const char* text; };", "inline const Entry kEntries[] = {"]


def esc(s):
    return s.replace("\\", "\\\\").replace('"', '\\"')


def unjs(s):
    return re.sub(r"\\u([0-9a-fA-F]{4})", lambda m: chr(int(m.group(1), 16)), s).replace("\\'", "'")


n = 0
for m in re.finditer(r'^(\w+): \{ name: "([^"]*)", range: "([^"]*)", text: "((?:[^"\\]|\\.)*)"( \+ SONGWIDE)? \},?$', block, re.M):
    cid, name, rng, text, sw = m.groups()
    rng = unjs(rng).split(". ")[0].rstrip(".")           # the range itself; the plugin shows the setting live
    text = unjs(text) + (songwide if sw else "")
    if cid in NOT_YET:
        text += " (Not working yet in this build.)"
    out.append(f'    {{"{cid}", "{esc(unjs(name))}", "{esc(rng)}", "{esc(text)}"}},')
    n += 1
out += ["};", "constexpr int kNumEntries = int(sizeof(kEntries) / sizeof(kEntries[0]));", "}  // namespace help", ""]
open(os.path.join(HERE, "..", "plugin", "HelpText.h"), "w", encoding="utf-8").write("\n".join(out))
print("wrote plugin/HelpText.h,", n, "entries")
